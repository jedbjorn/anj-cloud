#!/usr/bin/env python3
"""Apply the deployment profile to a client source tree before a build.

    python3 apps/client/tool/apply_profile.py [--root DIR]

Writes two untracked files under DIR/apps/client (default: this checkout):
  assets/release/household-release-key.pub   the profile's release public key; header only when the
                                              profile has none (the app then has no desktop self-update)
  anj-defines.env                            ANJ_HOUSEHOLD_ORIGIN=<origin>, for
                                              `flutter build --dart-define-from-file=anj-defines.env`;
                                              absent when the profile is the placeholder
The profile is deploy/deployment_profile.py's (ANJ_PROFILE, ~/.local/share/anj-cloud/profile.toml,
deploy/.local/profile.toml). Both outputs are gitignored: a source archive never carries them, so every
release build runs this (or `render()` below) on its own tree.
"""

import argparse
from pathlib import Path
import sys

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO))

from deploy import deployment_profile  # noqa: E402

KEY_FILE = "assets/release/household-release-key.pub"
DEFINES_FILE = "anj-defines.env"
HEADER = ("# AnJ Cloud household release key, generated by apps/client/tool/apply_profile.py from the\n"
          "# deployment profile ([release] public_key). Not tracked. The private key never leaves your host.\n")


def render(profile):
    """{relative path under apps/client: text} for a profile."""
    key = (profile["release"].get("public_key") or "").strip()
    files = {KEY_FILE: HEADER + (key + "\n" if key else "")}
    if not profile["placeholder"] and profile["gateway"].get("origin"):
        files[DEFINES_FILE] = f"ANJ_HOUSEHOLD_ORIGIN={profile['gateway']['origin']}\n"
    return files


def apply(root=REPO, profile=None):
    profile = profile or deployment_profile.load()
    client = Path(root) / "apps/client"
    for relative in (KEY_FILE, DEFINES_FILE):
        (client / relative).unlink(missing_ok=True)
    written = render(profile)
    for relative, text in written.items():
        target = client / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
    return sorted(written)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--root", type=Path, default=REPO)
    options = parser.parse_args()
    for relative in apply(options.root):
        print(f"wrote apps/client/{relative}")


if __name__ == "__main__":
    main()
