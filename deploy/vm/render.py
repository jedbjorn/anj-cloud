"""Render the production HAProxy config and PM2 ecosystem (spec #20 rev7; stdlib only).

`haproxy(template, bind_address=…, household_lan=…, vm_gid=…)` fills deploy/prod/haproxy.cfg.tmpl;
`ecosystem(…)` returns deploy/vm/ecosystem.config.js content with one PM2 app per stack service.
prod.py writes both into state/release/<commit12>/; the bootstrap (spec #21) passes the bind
address and household LAN to `prod.py setup`.
"""

import ipaddress
import json
import re

try:
    from . import paths
except ImportError:
    import paths

PLACEHOLDER = re.compile(r"\{\{([A-Z_]+)\}\}")


def haproxy(template, *, bind_address=paths.DEFAULT_BIND_ADDRESS, household_lan=paths.DEFAULT_HOUSEHOLD_LAN, vm_gid):
    address = ipaddress.ip_address(bind_address)
    if address.version != 4 or address.is_unspecified or address.is_loopback:
        raise ValueError("HAProxy binds one specific IPv4 address of the VM")
    network = ipaddress.ip_network(household_lan, strict=True)
    if network.version != 4 or not network.is_private:
        raise ValueError("The household LAN must be a private IPv4 network")
    if not isinstance(vm_gid, int) or vm_gid <= 0:
        raise ValueError("The admin socket group must be the VM user's non-root gid")
    values = {"BIND_ADDRESS": str(address), "BIND_PORT": str(paths.BIND_PORT), "HOUSEHOLD_LAN": str(network),
              "HOUSEHOLD_ACL": str(paths.HOUSEHOLD_ACL), "ADMIN_SOCKET": str(paths.HAPROXY_ADMIN_SOCKET),
              "VM_GID": str(vm_gid), "GATEWAY_SOCKET": str(paths.GATEWAY_SOCKET), "GATEWAY_GID": str(paths.GATEWAY_GID)}
    names = set(PLACEHOLDER.findall(template))
    if names - set(values):
        raise ValueError("Unknown HAProxy template placeholders: " + ", ".join(sorted(names - set(values))))
    return PLACEHOLDER.sub(lambda match: values[match.group(1)], template)


def ecosystem(*, state_root=paths.STATE_ROOT, bin_dir=None, python="/usr/bin/python3", project=paths.PROJECT):
    """One PM2 app per stack service, each `run-service <app>` attached (decision #85)."""
    bin_dir = bin_dir or (state_root / "bin" if hasattr(state_root, "__truediv__") else paths.BIN_DIR)
    apps = []
    for app in paths.STACK_APPS:
        entry = {
            "name": app,
            "script": str(bin_dir / "run-service"),
            "interpreter": python,
            "interpreter_args": "-I",
            "args": [app, "--state-root", str(state_root), "--project", project],
            "cwd": str(state_root),
            "autorestart": True,
            "exp_backoff_restart_delay": 1000,
            "kill_timeout": paths.KILL_TIMEOUT_MS,
            "treekill": False,
            "stop_exit_codes": [paths.EMERGENCY_EXIT_CODE],
            "merge_logs": True,
            "time": True,
            # No __pycache__ in state/bin (the private state tree; run-service also sets it itself).
            "env": {"PYTHONUNBUFFERED": "1", "PYTHONDONTWRITEBYTECODE": "1"},
        }
        if app in paths.QUIET_APPS:
            # No Nextcloud access line (file paths) or backend output in PM2 logs (#68 (5)).
            entry["out_file"] = "/dev/null"
            entry["error_file"] = "/dev/null"
        apps.append(entry)
    return ("// Generated by deploy/vm/render.py for " + project + "; do not edit (spec #20 rev7).\n"
            "module.exports = " + json.dumps({"apps": apps}, indent=2) + ";\n")
