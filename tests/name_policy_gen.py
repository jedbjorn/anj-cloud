"""Generate the portable-name tables and shared test vectors (decision #120, seam S1).

One generator feeds both implementations of the name policy, so they cannot drift:

- `services/access/name_tables.py` and `apps/client/lib/core/sync/name_tables.dart` hold the
  same Unicode data (canonical decompositions, canonical combining classes, full case folding),
  taken from this Python's `unicodedata`. The gateway and the clients use these tables, never
  their runtime's own Unicode library, so a Python or Dart upgrade cannot change a fold key.
- `tests/name_policy_vectors.json` holds the vectors both test suites run: name checks with
  their expected reasons, fold keys computed independently with `unicodedata`, and sibling
  clashes. Its NFC vectors are run by the clients, which upload and move names in NFC
  (decision #138) with the primary composites of the Dart tables.

    python3 tests/name_policy_gen.py           # rewrite the three files
    python3 tests/name_policy_gen.py --check   # exit 1 when any file is out of date

Regenerate only with a Python whose Unicode version is the one recorded in the tables, or on
purpose to move every implementation to a new Unicode version at once.
"""

import argparse
import json
from pathlib import Path
import random
import sys
import unicodedata

ROOT = Path(__file__).resolve().parent.parent
PYTHON_TABLES = ROOT / "services/access/name_tables.py"
DART_TABLES = ROOT / "apps/client/lib/core/sync/name_tables.dart"
VECTORS = ROOT / "tests/name_policy_vectors.json"

HANGUL = range(0xAC00, 0xD7A4)
SURROGATES = range(0xD800, 0xE000)


def code_points():
    for cp in range(0x110000):
        if cp not in SURROGATES:
            yield cp


def tables():
    decomposition, combining, casefold = {}, {}, {}
    for cp in code_points():
        char = chr(cp)
        if cp not in HANGUL:
            nfd = unicodedata.normalize("NFD", char)
            if nfd != char:
                decomposition[cp] = [ord(c) for c in nfd]
        if unicodedata.combining(char):
            combining[cp] = unicodedata.combining(char)
        folded = char.casefold()
        if folded != char:
            casefold[cp] = [ord(c) for c in folded]
    return decomposition, combining, casefold


def compositions():
    """Primary composites: (first, second) -> composite for every canonical pair decomposition
    that NFC recomposes (composition exclusions and singletons excluded; Hangul is algorithmic)."""
    pairs = {}
    for cp in code_points():
        if cp in HANGUL:
            continue
        mapping = unicodedata.decomposition(chr(cp))
        if not mapping or mapping.startswith("<"):
            continue
        parts = [int(part, 16) for part in mapping.split()]
        if len(parts) == 2 and unicodedata.normalize("NFC", unicodedata.normalize("NFD", chr(cp))) == chr(cp):
            pairs[(parts[0], parts[1])] = cp
    return pairs


def reference_key(name):
    """Canonical caseless matching (Unicode D145): NFD(casefold(NFD(name)))."""
    return unicodedata.normalize("NFD", unicodedata.normalize("NFD", name).casefold())


def python_tables(decomposition, combining, casefold):
    def mapping(name, data, value):
        lines = [f"{name} = {{"]
        row = []
        for cp in sorted(data):
            row.append(f"0x{cp:X}: {value(data[cp])},")
            if len(row) == 6:
                lines.append("    " + " ".join(row))
                row = []
        if row:
            lines.append("    " + " ".join(row))
        lines.append("}")
        return "\n".join(lines)

    sequence = lambda values: "(" + ", ".join(f"0x{v:X}" for v in values) + ("," if len(values) == 1 else "") + ")"
    return "\n\n".join([
        '"""Generated by tests/name_policy_gen.py; do not edit. Unicode data for the portable-name policy."""',
        f'UNICODE_VERSION = "{unicodedata.unidata_version}"',
        "# Full canonical decomposition of each code point that has one (Hangul syllables are algorithmic).",
        mapping("DECOMPOSITION", decomposition, sequence),
        "# Canonical combining class of each code point whose class is not 0.",
        mapping("COMBINING", combining, str),
        "# Full case folding (CaseFolding.txt statuses C and F), as str.casefold applies it.",
        mapping("CASEFOLD", casefold, sequence),
    ]) + "\n"


def dart_tables(decomposition, combining, casefold):
    def mapping(name, kind, data, value):
        lines = [f"const Map<int, {kind}> {name} = {{"]
        row = []
        for cp in sorted(data):
            row.append(f"0x{cp:X}: {value(data[cp])},")
            if len(row) == 6:
                lines.append("  " + " ".join(row))
                row = []
        if row:
            lines.append("  " + " ".join(row))
        lines.append("};")
        return "\n".join(lines)

    sequence = lambda values: "[" + ", ".join(f"0x{v:X}" for v in values) + "]"
    return "\n\n".join([
        "// Generated by tests/name_policy_gen.py; do not edit.\n"
        "// Unicode data for the portable-name policy (decision #120). The gateway's\n"
        "// services/access/name_tables.py holds the same data.\n"
        "// dart format off\n"
        "library;",
        f"const nameTablesUnicodeVersion = '{unicodedata.unidata_version}';",
        "/// Full canonical decomposition of each code point that has one (Hangul\n"
        "/// syllables are algorithmic).",
        mapping("nameDecomposition", "List<int>", decomposition, sequence),
        "/// Canonical combining class of each code point whose class is not 0.",
        mapping("nameCombiningClass", "int", combining, str),
        "/// Full case folding (CaseFolding.txt statuses C and F).",
        mapping("nameCaseFold", "List<int>", casefold, sequence),
        "/// Primary composites for NFC (decision #138), keyed by\n"
        "/// `first * 0x110000 + second` (Hangul syllables are algorithmic).",
        mapping("nameComposition", "int", {a * 0x110000 + b: c for (a, b), c in compositions().items()},
                lambda value: f"0x{value:X}"),
    ]) + "\n"


# Expected reasons are written by hand: they are the policy (decision #120), not derived from
# either implementation. None means the name is portable.
CHECKS = [
    ("report.txt", None), ("Documents", None), ("a", None), ("雪.txt", None), ("café.txt", None),
    ("café.txt", None), (".bashrc", None), (".env", None), (".config", None), (".git", None),
    (".hidden.txt", None), ("a.b.c", None), (" leading space", None), ("name with spaces.txt", None),
    ("100% done.txt", None), ("hash#.txt", None), ("a%20.txt", None), ("emoji 😀.png", None),
    ("CONSOLE", None), ("CONFIG.SYS", None), ("COM", None), ("COM0", None), ("COM10", None),
    ("LPT0", None), ("LPT10", None), ("NULL", None), ("AUXILIARY.txt", None), ("PRN1", None),
    ("xCON", None), ("CON-1", None), ("CON_", None), ("COM¹", None), ("ＣＯＮ", None),
    ("del\x7fname", None), ("tab nbsp", None), ("C1\u0085control", None), ("a.", "trailingDotOrSpace"),
    ("CON", "reserved"), ("con", "reserved"), ("Con", "reserved"), ("PRN", "reserved"), ("aux", "reserved"),
    ("NUL", "reserved"), ("nul.txt", "reserved"), ("CON.txt", "reserved"), ("con.tar.gz", "reserved"),
    ("Aux.Docx", "reserved"), ("CON .txt", "reserved"), ("nul  .txt", "reserved"), ("PRN.", "reserved"),
    *[(f"COM{n}", "reserved") for n in range(1, 10)], *[(f"lpt{n}.log", "reserved") for n in range(1, 10)],
    ("report.", "trailingDotOrSpace"), ("report ", "trailingDotOrSpace"), ("...", "trailingDotOrSpace"),
    ("trailing. ", "trailingDotOrSpace"), (".env.", "trailingDotOrSpace"), ("a  ", "trailingDotOrSpace"),
    *[(f"a{c}b", "invalidCharacter") for c in '<>:"/\\|?*'],
    *[(f"x{chr(cp)}y", "invalidCharacter") for cp in range(0x20)],
    ("CON<", "invalidCharacter"), ("bad:name.", "invalidCharacter"), ("", "empty"),
]

CLASHES = [
    ("a.txt", ["A.txt"], "A.txt"), ("A.txt", ["a.txt", "b.txt"], "a.txt"), ("a.txt", ["a.txt"], None),
    ("a.txt", ["b.txt", "c.txt"], None), ("README", ["readme", "ReadMe"], "readme"), ("x", [], None),
    ("café.txt", ["café.txt"], "café.txt"), ("café.txt", ["café.txt"], "café.txt"),
    ("Café.txt", ["café.TXT"], "café.TXT"), ("Straße", ["STRASSE"], "STRASSE"),
    ("K", ["k"], "k"), ("Ω", ["Ω"], "Ω"), (".bashrc", [".BASHRC"], ".BASHRC"),
    ("photo.JPG", ["photo.jpg", "photo.jpeg"], "photo.jpg"), ("Ǆ", ["ǅ", "ǆ"], "ǅ"),
    ("한", ["한"], "한"), ("é", ["e"], None), ("a", ["á"], None),
]


def vectors(decomposition, combining, casefold):
    special = sorted(set(decomposition) | set(combining) | set(casefold))
    pool = special + list(range(0x20, 0x7F)) + [0xAC00, 0xAC01, 0xD7A3, 0x1100, 0x1161, 0x11A8, 0x11C2, 0x0345, 0x0301, 0x0323]
    rng = random.Random(120)
    samples = [
        "A.txt", "Straße", "ΣΑΣ", "ﬃ", "İstanbul", "ǅ", "ᾼ", "ᾴ", "ᾴ", "ᾴ",
        "ạ́", "ạ́", "ẛ̣", "한국어", "한", "각", "Å", "Å",
        "ŉ", "ΐ", "ﬅ", "𐐀", "😀", "\U0001e900", "x",
    ]
    for _ in range(1500):
        samples.append("".join(chr(rng.choice(pool)) for _ in range(rng.randint(1, 6))))
    fold = [{"name": name, "key": reference_key(name)} for name in samples]
    nfc = [{"name": name, "nfc": unicodedata.normalize("NFC", name)}
           for name in samples + [unicodedata.normalize("NFD", name) for name in samples]]
    return {
        "about": "Generated by tests/name_policy_gen.py. Run by tests/test_portable_names.py and "
                 "apps/client/test/name_policy_test.dart. Fold keys come from unicodedata: NFD(casefold(NFD(name))).",
        "unicode": unicodedata.unidata_version,
        "check": [{"name": name, "reason": reason} for name, reason in CHECKS],
        "fold": fold,
        "clash": [{"name": name, "siblings": siblings, "clash": clash} for name, siblings, clash in CLASHES],
        "nfc": nfc,
    }


def outputs():
    data = tables()
    return {
        PYTHON_TABLES: python_tables(*data),
        DART_TABLES: dart_tables(*data),
        VECTORS: json.dumps(vectors(*data), ensure_ascii=True, indent=1) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when a generated file differs")
    options = parser.parse_args()
    stale = []
    for path, text in outputs().items():
        if options.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        print("Out of date (Unicode " + unicodedata.unidata_version + "): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
