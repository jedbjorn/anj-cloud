HANGUL = range(0xAC00, 0xD7A4)
SURROGATES = range(0xD800, 0xE000)


def code_points():
    for cp in range(0x110000):
        if cp not in SURROGATES:
            yield cp


def tables():
    decomposition, combining, casefold = {}, {}, {}
    for cp in code_points():
        char = chr(cp)
        if cp not in HANGUL:
            nfd = unicodedata.normalize("NFD", char)
            if nfd != char:
                decomposition[cp] = [ord(c) for c in nfd]
        if unicodedata.combining(char):
            combining[cp] = unicodedata.combining(char)
        folded = char.casefold()
        if folded != char:
            casefold[cp] = [ord(c) for c in folded]
    return decomposition, combining, casefold


def compositions():
    """Primary composites: (first, second) -> composite for every canonical pair decomposition
    that NFC recomposes (composition exclusions and singletons excluded; Hangul is algorithmic)."""
    pairs = {}
    for cp in code_points():
        if cp in HANGUL:
            continue
        mapping = unicodedata.decomposition(chr(cp))
        if not mapping or mapping.startswith("<"):
            continue
        parts = [int(part, 16) for part in mapping.split()]
        if len(parts) == 2 and unicodedata.normalize("NFC", unicodedata.normalize("NFD", chr(cp))) == chr(cp):
            pairs[(parts[0], parts[1])] = cp
    return pairs


def reference_key(name):
    """Canonical caseless matching (Unicode D145): NFD(casefold(NFD(name)))."""
    return unicodedata.normalize("NFD", unicodedata.normalize("NFD", name).casefold())


def python_tables(decomposition, combining, casefold):
    def mapping(name, data, value):
        lines = [f"{name} = {{"]
        row = []
        for cp in sorted(data):
            row.append(f"0x{cp:X}: {value(data[cp])},")
            if len(row) == 6:
                lines.append("    " + " ".join(row))
                row = []
        if row:
            lines.append("    " + " ".join(row))
        lines.append("}")
        return "\n".join(lines)

    sequence = lambda values: "(" + ", ".join(f"0x{v:X}" for v in values) + ("," if len(values) == 1 else "") + ")"
    return "\n\n".join([
        '"""Generated by tests/name_policy_gen.py; do not edit. Unicode data for the portable-name policy."""',
        f'UNICODE_VERSION = "{unicodedata.unidata_version}"',
        "# Full canonical decomposition of each code point that has one (Hangul syllables are algorithmic).",
        mapping("DECOMPOSITION", decomposition, sequence),
        "# Canonical combining class of each code point whose class is not 0.",
        mapping("COMBINING", combining, str),
        "# Full case folding (CaseFolding.txt statuses C and F), as str.casefold applies it.",
        mapping("CASEFOLD", casefold, sequence),
    ]) + "\n"


def dart_tables(decomposition, combining, casefold):
    def mapping(name, kind, data, value):
        lines = [f"const Map<int, {kind}> {name} = {{"]
        row = []
        for cp in sorted(data):
            row.append(f"0x{cp:X}: {value(data[cp])},")
            if len(row) == 6:
                lines.append("  " + " ".join(row))
